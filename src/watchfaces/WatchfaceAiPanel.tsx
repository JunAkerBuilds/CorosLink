function WatchmakerError({ message }: { message: PanelMessage }) {
  // Recognize older saved errors too; new runs carry a stable error code.
  const missing = message.errorCode === "CODEX_CLI_NOT_FOUND" || message.error?.startsWith("Codex CLI was not found.");
  const unavailable = message.errorCode === "CODEX_CLI_UNAVAILABLE" || message.error?.startsWith("Codex launchers were found, but none passed the launch check.");
  if (!missing && !unavailable) return <div className="wf-ai-error-card" role="alert"><CircleAlert size={14} aria-hidden="true" /><span>{message.error}</span></div>;
  return <div className="wf-ai-cli-setup" role="alert">
    <div className="wf-ai-cli-setup-heading"><Terminal size={17} aria-hidden="true" /><strong>{missing ? "Codex CLI needs to be installed" : "Codex CLI needs repair"}</strong></div>
    <p>{missing
      ? "CorosLink couldn’t find Codex CLI on this computer. It’s a separate terminal app required by this engine."
      : "CorosLink found Codex CLI, but it couldn’t start. The installation may be incomplete or out of date."}</p>
    <ol>
      <li><a href="https://learn.chatgpt.com/docs/codex/cli#getting-started" target="_blank" rel="noopener noreferrer">{missing ? "Follow OpenAI’s installation steps" : "Update or reinstall using OpenAI’s guide"}<ArrowUpRight size={12} aria-hidden="true" /></a> for your operating system.</li>
      <li>Open Terminal (PowerShell on Windows), run <code>codex</code>, and follow the sign-in prompts.</li>
      <li>Return here and send your message again.</li>
    </ol>
    <p className="wf-ai-cli-setup-note">Your face and chat are still here. Once Codex CLI is ready, send your message again.</p>
    <details><summary>Technical details</summary><pre>{message.error}</pre></details>
  </div>;
}

function GeneratedArtwork({ image, copyImage }: { image: GeneratedImage; copyImage: (assetId: string) => Promise<void> }) {
  const [status, setStatus] = useState<"idle" | "copying" | "copied" | "error">("idle");
  const [error, setError] = useState("");
  useEffect(() => {
    if (status !== "copied") return;
    const timer = window.setTimeout(() => setStatus("idle"), 2000);
    return () => window.clearTimeout(timer);
  }, [status]);
  const copy = async () => {
    setStatus("copying");
    setError("");
    try {
      await copyImage(image.assetId);
      setStatus("copied");
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "Could not copy the original image. Try again.");
      setStatus("error");
    }
  };
  return (
    <figure>
      <img src={image.dataUrl} alt="Image generated by Watchmaker" />
      <button type="button" className="wf-ai-copy-image" onClick={() => void copy()} disabled={status === "copying"}
        aria-label={status === "copied" ? "Image copied" : `Copy image (${image.width} by ${image.height} pixels)`}
        title={status === "copied" ? "Copied" : "Copy full-resolution image"}>
        {status === "copying" ? <LoaderCircle size={13} className="wf-ai-spin" aria-hidden="true" />
          : status === "copied" ? <Check size={13} aria-hidden="true" /> : <Copy size={13} aria-hidden="true" />}
        <span>{status === "copied" ? "Copied" : "Copy"}</span>
      </button>
      <figcaption>{image.width}×{image.height}</figcaption>
      <span className="wf-ai-copy-status" role="status">{status === "copied" ? "Image copied to clipboard" : ""}</span>
      {error ? <div className="wf-ai-copy-error" role="alert">{error}</div> : null}
    </figure>
  );
}

