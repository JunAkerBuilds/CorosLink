const CLI_WARNING_KEY = "coroslink.watchfaceAi.cliWarningAcknowledged.v1";

function newId(): string {
  return typeof crypto !== "undefined" && "randomUUID" in crypto
    ? crypto.randomUUID()
    : `${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

function readPreference(key: string): string {
  try { return window.localStorage.getItem(key) ?? ""; } catch { return ""; }
}

function writePreference(key: string, value: string): void {
  try { window.localStorage.setItem(key, value); } catch { /* preference only */ }
}

/** Decodes any pasted image and re-encodes it as a bounded PNG data URL. */
async function toPngDataUrl(file: Blob): Promise<string> {
  const bitmap = await createImageBitmap(file);
  try {
    const scale = Math.min(1, MAX_IMAGE_EDGE / Math.max(bitmap.width, bitmap.height));
    const canvas = document.createElement("canvas");
    canvas.width = Math.max(1, Math.round(bitmap.width * scale));
    canvas.height = Math.max(1, Math.round(bitmap.height * scale));
    canvas.getContext("2d")!.drawImage(bitmap, 0, 0, canvas.width, canvas.height);
    return canvas.toDataURL("image/png");
  } finally {
    bitmap.close();
  }
}

/** Rebuilds panel messages from a saved chat, tolerating older or partial shapes. */
function restoreMessages(raw: unknown[]): PanelMessage[] {
  const strings = (value: unknown) =>
    Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : [];
  return raw.flatMap((item) => {
    if (!item || typeof item !== "object") return [];
    const message = item as Partial<PanelMessage>;
    if (message.role !== "user" && message.role !== "assistant") return [];
    return [{
      id: typeof message.id === "string" ? message.id : newId(),
      role: message.role,
      content: typeof message.content === "string" ? message.content : "",
      images: strings(message.images),
      ...(message.imageRole ? { imageRole: message.imageRole } : {}),
      steps: Array.isArray(message.steps) ? message.steps.filter((step) => step && typeof step.tool === "string") : [],
      previews: strings(message.previews),
      generated: Array.isArray(message.generated)
        ? message.generated.filter((image) => image && typeof image.assetId === "string" && typeof image.dataUrl === "string")
        : [],
      thinking: "",
      ...(message.memory?.version === 1 && Array.isArray(message.memory.entries) ? { memory: message.memory } : {}),
      ...(typeof message.error === "string" ? { error: message.error } : {}),
      ...(["CODEX_CLI_NOT_FOUND", "CODEX_CLI_UNAVAILABLE"].includes(message.errorCode ?? "") ? { errorCode: message.errorCode } : {}),
      ...(message.cancelled ? { cancelled: true } : {}),
      ...(message.changed ? { changed: true } : {})
    }];
  });
}

function chatTitle(messages: PanelMessage[]): string {
  const first = messages.find((message) => message.role === "user");
  const text = first?.content.trim().replace(/\s+/g, " ");
  if (text) return text.length > 60 ? `${text.slice(0, 57)}…` : text;
  return first?.images.length ? "Image reference" : "New chat";
}

function relativeTime(iso: string): string {
  const then = Date.parse(iso);
  if (!Number.isFinite(then)) return "";
  const minutes = Math.round((Date.now() - then) / 60_000);
  if (minutes < 1) return "Just now";
  if (minutes < 60) return `${minutes}m ago`;
  const hours = Math.round(minutes / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.round(hours / 24);
  if (days < 7) return `${days}d ago`;
  return new Date(then).toLocaleDateString();
}

function stepLabel(step: ToolStep): string {
  const labels = TOOL_LABELS[step.tool];
  if (!labels) return step.tool;
  return step.status === "call" ? `${labels[0]}…` : step.status === "done" ? labels[1] : `${labels[0]} failed`;
}

