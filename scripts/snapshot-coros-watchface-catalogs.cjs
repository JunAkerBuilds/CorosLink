#!/usr/bin/env electron
// Snapshots the COROS editable-template catalog for every supported watch into
// electron/watchfaceCatalogSnapshot.ts, so Watch Faces can list templates
// without a COROS sign-in (the template packages themselves are public).
// Runs under Electron because it reads the signed-in mobile session that the
// local CorosLink install stored with safeStorage.
//
//   npm run watchfaces:snapshot
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { app } = require("electron");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "electron", "watchfaceCatalogSnapshot.ts");
const userData = process.env.COROSLINK_USER_DATA
  ?? path.join(os.homedir(), "Library", "Application Support", "coroslink");
// safeStorage keys the keychain entry by app name; match the dev instance.
app.setName(process.env.COROSLINK_APP_NAME ?? "coroslink");
app.setPath("userData", userData);

const FIELDS = [
  "id", "name", "category", "sourceTemplateId", "firmwareType", "previewImageUrl",
  "packageUrl", "backgroundImageId", "watchFaceVersion", "diyVersion", "templateType"
];

/** CorosWatchfaceTheme keys in a fixed order, so reruns diff cleanly. */
function compact(theme) {
  const entry = {};
  for (const key of FIELDS) {
    if (theme[key] !== undefined && theme[key] !== "") entry[key] = theme[key];
  }
  return entry;
}

async function main() {
  await app.whenReady();
  const { initializeDatabase } = require("../dist-electron/database.js");
  initializeDatabase(userData);
  const service = require("../dist-electron/corosWatchfaceService.js");
  const { WATCHFACE_TARGETS } = require("../dist-electron/watchfaceTargets.js");
  if (!(await service.getCorosWatchfaceStatus()).authenticated) {
    throw new Error("Sign in to COROS in Watch Faces first: the catalog needs a mobile session.");
  }

  const templates = {};
  for (const target of WATCHFACE_TARGETS) {
    const themes = await service.listCorosWatchfaceThemes({
      firmwareType: target.firmwareType, language: "en-US", maxWatchFaceVersion: 5, catalog: "editable"
    });
    templates[target.firmwareType] = {
      savedAt: new Date().toISOString(),
      themes: themes.filter((theme) => theme.packageUrl).map(compact)
    };
    console.log(`${target.label} (${target.firmwareType}): ${themes.length} templates`);
  }

  const source = [
    "// Generated by scripts/snapshot-coros-watchface-catalogs.cjs (npm run watchfaces:snapshot).",
    "// Do not edit by hand: rerun the script while signed in to COROS.",
    'import type { CorosWatchfaceThemeCacheEntry } from "./types";',
    "",
    "/** COROS editable templates (en-US, max version 5) by firmware type. */",
    `export const WATCHFACE_TEMPLATE_SNAPSHOT: Record<string, CorosWatchfaceThemeCacheEntry> = ${JSON.stringify(templates, null, 2)};`,
    ""
  ].join("\n");
  await fs.writeFile(outputPath, source);
  console.log(`Wrote ${path.relative(root, outputPath)} (${(Buffer.byteLength(source) / 1024).toFixed(0)} KB)`);
}

main()
  .catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  })
  .finally(() => app.quit());
