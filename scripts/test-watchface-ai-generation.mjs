import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { prepareGeneration } = require('../dist-electron/watchfaceAiGeneration.js');
const { WatchfaceAssetReview } = require('../dist-electron/watchfaceAiAssetReview.js');
const reviews = new WatchfaceAssetReview(), attempts = [];
const brief = { purpose: 'font-set', role: 'clock', strategy: 'atlas', characters: '0123456789', sampleAssetId: 'sample' };
assert.throws(() => prepareGeneration(brief, attempts, reviews), /font-sample/);
assert.throws(() => prepareGeneration({ ...brief, purpose: 'font-sample' }, attempts, reviews), /at most four/);
reviews.register('sample', 0, ['reference']);
attempts.push({ purpose: 'font-sample', role: 'clock', strategy: 'group', characters: '028', assetId: 'sample' });
assert.throws(() => prepareGeneration(brief, attempts, reviews), /visually accept/);
reviews.review([{ assetId: 'sample', status: 'accepted', comparison: 'Heavy forward-slanted sans-serif matches the reference clock.', referenceAssetIds: ['reference'] }], 1);
assert.doesNotThrow(() => prepareGeneration(brief, attempts, reviews));
assert.throws(() => prepareGeneration({ ...brief, role: 'metrics' }, attempts, reviews), /font-sample/);
reviews.register('atlas', 1, ['reference']);
reviews.review([{ assetId: 'atlas', status: 'rejected', comparison: 'The atlas lost the matching slant and joined neighboring strokes.', referenceAssetIds: ['reference'] }], 2);
attempts.push({ ...brief, assetId: 'atlas' });
assert.throws(() => prepareGeneration(brief, attempts, reviews), /smaller groups/);
assert.doesNotThrow(() => prepareGeneration({ ...brief, strategy: 'group', characters: '012' }, attempts, reviews));
attempts.push({ ...brief, strategy: 'group', failed: true });
assert.throws(() => prepareGeneration({ ...brief, strategy: 'group', characters: '012' }, attempts, reviews), /individual glyphs/);
assert.doesNotThrow(() => prepareGeneration({ ...brief, strategy: 'individual', characters: '0' }, attempts, reviews));
const background = prepareGeneration({ purpose: 'background', role: 'neon', staticElements: ['full circles for KM, steps, calories and BPM', 'mountain contours'], liveElements: ['battery ring', 'clock digits', 'metric values'] }, attempts, reviews);
assert.match(background.constraints, /Static artwork only: full circles/);
assert.match(background.constraints, /Exclude completely.*battery ring/);
assert.throws(() => prepareGeneration({ purpose: 'background', role: 'neon' }, attempts, reviews), /staticElements and liveElements/);
console.log('Watchmaker generation recovery tests passed.');
