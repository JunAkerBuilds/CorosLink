import React from "react";
import { createRoot } from "react-dom/client";
import L from "leaflet";
import "leaflet/dist/leaflet.css";
import { MapSettings } from "../../src/settings/MapSettings";
import { baseTileLayer } from "../../src/maps/baseTileLayer";
import { ROUTE_BASE_LAYERS } from "../../src/maps/routes/constants";
import { withCartoApiKey, readCartoApiKey } from "../../src/maps/cartoApiKey";
import "../../src/styles.css";
const map = L.map("map").setView([0, 0], 1);
const light = baseTileLayer(ROUTE_BASE_LAYERS.light.url, { attribution: ROUTE_BASE_LAYERS.light.attribution }).addTo(map);
const dark = baseTileLayer(ROUTE_BASE_LAYERS.dark.url, {}).addTo(map);
const street = baseTileLayer(ROUTE_BASE_LAYERS.street.url, {}).addTo(map);
Object.assign(window, { map, light, dark, street, withCartoApiKey, readCartoApiKey });
createRoot(document.getElementById("root")!).render(<MapSettings />);
