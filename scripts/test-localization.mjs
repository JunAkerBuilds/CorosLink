import assert from 'node:assert/strict';
import { frenchMessages, translate, t, resolveLanguage, getLanguage, getLocale, setLanguage, initializeLanguage, subscribeLanguage, formatDate, formatNumber, LANGUAGE_STORAGE_KEY } from '../src/i18n/locale.ts';
import { t as trainingT } from '../src/i18n/trainingLocale.ts';
import { t as watchfaceT } from '../src/i18n/watchfacesLocale.ts';
import { t as toolsT } from '../src/i18n/toolsLocale.ts';
import { formatDistanceValue, formatWeightValue, formatSpeedValue, formatPaceValue, displayDistanceToMeters } from '../src/units/units.ts';

const storage = new Map();
const nativeCalls = [];
globalThis.window = { localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) }, corosLink: { setLanguage: async language => { nativeCalls.push(language); } } };
globalThis.document = { documentElement: { lang: '' } };
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { language: 'fr-CA', languages: ['fr-CA', 'en-US'] } });
assert.equal(resolveLanguage('fr-CA'), 'fr');
assert.equal(resolveLanguage('FR_fr'), 'fr');
assert.equal(resolveLanguage('de-DE'), 'en');
assert.equal(resolveLanguage(null), 'en');
initializeLanguage();
assert.equal(getLanguage(), 'fr');
assert.equal(document.documentElement.lang, 'fr');
assert.equal(storage.get(LANGUAGE_STORAGE_KEY), 'fr');
assert.equal(getLocale(), 'fr-FR');
assert.equal(t('Settings'), 'Paramètres');
assert.equal(trainingT('Weight'), 'Poids');
assert.equal(watchfaceT('Weight'), 'Graisse');
assert.equal(trainingT('Stroke'), 'Nage');
assert.equal(watchfaceT('Stroke'), 'Contour');
assert.equal(toolsT('Open'), 'Ouvrir');
assert.equal(t('No translation yet'), 'No translation yet');
assert.equal(t('constructor'), 'constructor');
assert.equal(t('__proto__'), '__proto__');
assert.equal(t('toString'), 'toString');
assert.equal(t('Delete "{{value0}}" locally?', { value0: '$& <script> Élodie' }), 'Supprimer « $& <script> Élodie » de cet ordinateur ?');
assert.equal(t('Startup view: {{value0}}', { value0: undefined }), 'Vue de démarrage : ');
assert.equal(formatNumber(1234.5), new Intl.NumberFormat('fr-FR').format(1234.5));
assert.match(formatDate(new Date(2026, 9, 15), { month: 'long' }), /octobre/);
assert.equal(formatDistanceValue(1250, 'metric'), '1,25 km');
assert.equal(formatWeightValue(72.5, 'metric'), '72,5 kg');
assert.equal(formatSpeedValue(12.5, 'metric'), '12,5 km/h');
assert.equal(formatPaceValue(300, 'metric'), '5:00 /km');
assert.equal(displayDistanceToMeters(1.25, 'metric'), 1250);
let notifications = 0;
const unsubscribe = subscribeLanguage(() => notifications++);
setLanguage('en');
assert.equal(notifications, 1);
assert.equal(document.documentElement.lang, 'en');
assert.equal(t('Settings'), 'Settings');
assert.equal(formatDistanceValue(1250, 'metric'), '1.25 km');
setLanguage('en');
assert.equal(notifications, 1, 'unchanged preferences do not rerender');
unsubscribe();
setLanguage('fr');
assert.equal(notifications, 1);
storage.set(LANGUAGE_STORAGE_KEY, 'en');
initializeLanguage();
assert.equal(getLanguage(), 'en', 'explicit preference wins over French system locale');
window.localStorage.getItem = () => { throw new Error('blocked'); };
window.localStorage.setItem = () => { throw new Error('blocked'); };
initializeLanguage();
assert.equal(getLanguage(), 'fr', 'language selection works with restricted storage');
assert.ok(nativeCalls.includes('fr') && nativeCalls.includes('en'));
assert.ok(Object.keys(frenchMessages).length > 3000, 'catalog spans the desktop sections');
for (const [source, translation] of Object.entries(frenchMessages)) {
  assert.equal(typeof translation, 'string');
  assert.ok(translation.trim(), `Empty French translation: ${source}`);
  const sourceParameters = new Set([...source.matchAll(/\{\{(\w+)\}\}/g)].map(match => match[1]));
  const translatedParameters = [...translation.matchAll(/\{\{(\w+)\}\}/g)].map(match => match[1]);
  for (const parameter of translatedParameters) assert.ok(sourceParameters.has(parameter), `Unknown French interpolation ${parameter}: ${source}`);
  const values = Object.fromEntries([...sourceParameters].map(key => [key, 'literal $&']));
  assert.ok(!/\{\{\w+\}\}/.test(translate(source, 'fr', values)), `Unresolved interpolation: ${source}`);
}
console.log(`Localization passed: ${Object.keys(frenchMessages).length} French messages, preference persistence, safe interpolation, fallback, subscriptions, dates and units.`);
