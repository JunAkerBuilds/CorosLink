// CRC-16/CCITT-FALSE, as COROS's watch files use it. From CorosLink's corosBleRouteProtocol.ts (c2ff5110).
export function crc16Ccitt(data: Uint8Array): number {
  let crc = 0xffff;
  for (const byte of data) {
    crc ^= byte << 8;
    for (let bit = 0; bit < 8; bit++) crc = ((crc << 1) ^ (crc & 0x8000 ? 0x1021 : 0)) & 0xffff;
  }
  return crc;
}
