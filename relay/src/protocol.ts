export const ENVIRONMENT_ID_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;
/** Each link is a paid Cloudflare tunnel, so one account can link this many computers. */
export const MAX_LINKED_ENVIRONMENTS_PER_USER = 10;
export const SESSION_ID_PATTERN = /^[A-Za-z0-9_.:-]{1,128}$/;
export type EnvironmentPlatform = "darwin" | "win32" | "linux";
export const ENVIRONMENT_PLATFORMS: readonly EnvironmentPlatform[] = ["darwin", "win32", "linux"];

/** Public P-256 JWK. Private members (`d`) are refused. */
export interface EnvironmentPublicJwk {
  kty: "EC";
  crv: "P-256";
  x: string;
  y: string;
}

/**
 * `POST /v1/environments/link`. Auth: `Authorization: Bearer <website JWT>`
 * (client_id coroslink-desktop) and the environment signature with
 * op "environment.link", verified against `publicJwk`.
 */
export interface LinkRequest {
  environmentId: string;
  publicJwk: EnvironmentPublicJwk;
  label: string; // 1-64 characters, shown on the phone
  platform: EnvironmentPlatform;
  port: number; // loopback port of the desktop's environment server
}

export interface LinkResponse {
  environmentId: string;
  userId: string;
  hostname: string;
  httpBaseUrl: string;
  tunnelId: string;
  /** cloudflared connector token. Secret: keep it with safeStorage. */
  connectorToken: string;
  generation: number;
  /** RFC 7638 thumbprint of the linked environment key. */
  keyThumbprint: string;
}

/**
 * `POST /v1/environments/recovery`. Auth: environment signature with
 * op "environment.recovery". Send it at every startup (this is what
 * registers recovery) and whenever cloudflared exits or the tunnel is
 * rejected. At most once per RECOVERY_MIN_INTERVAL_SECONDS.
 */
export interface RecoveryRequest {
  environmentId: string;
  /** The tunnel the desktop's stored connector token belongs to, if any. */
  tunnelId: string | null;
  port: number;
}

export const RECOVERY_MIN_INTERVAL_SECONDS = 120;

export interface RecoveryResponse {
  environmentId: string;
  hostname: string;
  httpBaseUrl: string;
  tunnelId: string;
  generation: number;
  /**
   * unchanged: the stored connector is still right.
   * reconfigured: the tunnel's ingress now points at the new port.
   * reprovisioned: a new tunnel replaced a missing one; use connectorToken.
   */
  action: "unchanged" | "reconfigured" | "reprovisioned";
  /** Present when the request's tunnelId is not the allocation's tunnel. */
  connectorToken?: string;
}

/**
 * `POST /v1/environments/unlink`. Auth: either a website JWT (any client) or
 * the environment signature with op "environment.unlink".
 */
export interface UnlinkRequest {
  environmentId: string;
}

export interface UnlinkResponse {
  environmentId: string;
  unlinked: true;
  /** pending: teardown failed part way; the relay's cron retries it. */
  teardown: "complete" | "pending";
}

export type EnvironmentOnlineStatus = "online" | "offline" | "provisioning" | "unknown";
export type CloudflareTunnelStatus = "healthy" | "degraded" | "down" | "inactive";

/** `GET /v1/environments`. Auth: website JWT (any client). */
export interface EnvironmentSummary {
  environmentId: string;
  /**
   * RFC 7638 thumbprint of the desktop key the relay verifies mint answers
   * with. Phones pin it (from LAN pairing or first sight): a change means the
   * computer was unlinked and relinked with another key.
   */
  keyThumbprint: string;
  label: string;
  platform: EnvironmentPlatform;
  hostname: string | null;
  httpBaseUrl: string | null;
  status: EnvironmentOnlineStatus;
  tunnelStatus: CloudflareTunnelStatus | null;
  offlineReason?: "tunnel_released" | "busy";
  linkedAt: string;
}

export interface ListEnvironmentsResponse {
  environments: EnvironmentSummary[];
}

/**
 * `POST /v1/environments/:environmentId/connect`. Auth: website JWT
 * (client_id c-link-ios) and a DPoP proof (RFC 9449, ES256) in the `DPoP`
 * header with htm "POST", htu = relay origin + path, and
 * ath = base64url(SHA-256(website JWT)). Empty body.
 */
export interface ConnectResponse {
  environmentId: string;
  /** The key that signed this credential's mint answer; compare with the pinned one. */
  keyThumbprint: string;
  hostname: string;
  httpBaseUrl: string;
  /** One-time bootstrap credential bound to the DPoP key. Redeem at the desktop's /v1/auth/bootstrap. */
  credential: string;
  expiresAt: string;
}

/** `POST /v1/devices`. Auth: website JWT (client_id c-link-ios). */
export interface RegisterDeviceRequest {
  token: string; // APNs device token, hex
  environment: "sandbox" | "production";
}

export interface RegisterDeviceResponse {
  registered: true;
}

/** `DELETE /v1/devices`. Auth: website JWT. */
export interface UnregisterDeviceRequest {
  token: string;
}

