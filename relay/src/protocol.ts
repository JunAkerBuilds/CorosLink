// ---------------------------------------------------------------------------
// Errors: every non-2xx body is { error: { code, message } }
// ---------------------------------------------------------------------------

export const ERROR_CODES = [
  "invalid_request",
  "invalid_token", // 401: website JWT missing, expired, wrong iss/aud, unknown kid
  "client_not_allowed", // 403: right token, wrong client_id for this endpoint
  "invalid_signature", // 401: environment signature or DPoP proof failed
  "signature_replayed", // 401: nonce or jti already used
  "signature_stale", // 401: iat outside ±60 s; details.serverTime has the relay clock
  "environment_not_linked", // 404
  "environment_not_ready", // 409: the tunnel is still provisioning
  "link_limit_reached", // 409: MAX_LINKED_ENVIRONMENTS_PER_USER computers already linked
  "environment_key_mismatch", // 409: linked with another key; unlink first
  "allocation_conflict", // 409: a concurrent change won; retry
  "allocation_busy", // 503: cleanup holds the tunnel; retry after Retry-After
  "rate_limited", // 429: see Retry-After
  "environment_unreachable", // 502
  "environment_redirect_refused", // 502
  "environment_refused", // 502: the desktop answered the mint with an error
  "environment_response_invalid", // 502: mint response failed verification
  "upstream_error", // 502: Cloudflare API failed
  "upstream_rate_limited", // 503: Cloudflare API rate limit
  "not_configured", // 503: the relay is missing configuration for this endpoint
  "not_found",
  "method_not_allowed",
  "internal_error",
] as const;
export type ErrorCode = (typeof ERROR_CODES)[number];

export interface ErrorBody {
  error: {
    code: ErrorCode;
    message: string;
    details?: Record<string, string | number | boolean>;
  };
}

// ---------------------------------------------------------------------------
// Helpers shared by both sides
// ---------------------------------------------------------------------------

const textEncoder = new TextEncoder();

export function base64UrlEncode(bytes: Uint8Array | ArrayBuffer): string {
  const view = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  let binary = "";
  for (let index = 0; index < view.length; index += 1) {
    binary += String.fromCharCode(view[index]!);
  }
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/u, "");
}

export async function sha256Base64Url(data: Uint8Array | string): Promise<string> {
  const bytes = typeof data === "string" ? textEncoder.encode(data) : data;
  return base64UrlEncode(await crypto.subtle.digest("SHA-256", bytes));
}

/** `https://<hostname>` for a tunnel hostname. */
export function httpBaseUrlForHostname(hostname: string): string {
  return `https://${hostname}`;
}
