/**
 * CorosLink relay protocol, version 1.
 *
 * This file is the source of truth for everything that crosses the relay's
 * boundary: website JWT claims, environment (desktop) request signatures, the
 * mint exchange between the relay and a desktop, and every endpoint's request
 * and response bodies. PROTOCOL.md explains the same contract in prose.
 *
 * It has no imports and uses only WebCrypto, so the desktop (Node 20+, where
 * `globalThis.crypto` exists) and test fixtures can import it directly.
 */

export const RELAY_PROTOCOL_VERSION = 1;

// ---------------------------------------------------------------------------
// Website-issued user tokens (watchfaces.coroslink.com → relay)
// ---------------------------------------------------------------------------

/** OAuth client ids the website issues relay tokens to. */
export const WEBSITE_CLIENT_IDS = {
  ios: "c-link-ios",
  desktop: "coroslink-desktop",
} as const;
export type WebsiteClientId = (typeof WEBSITE_CLIENT_IDS)[keyof typeof WEBSITE_CLIENT_IDS];

/** A relay token may live at most this long (`exp - iat`). */
export const USER_TOKEN_MAX_LIFETIME_SECONDS = 600;

/**
 * Claims of the ES256 JWT the website mints at `POST /api/v1/app/relay-token`.
 * The protected header carries `alg: "ES256"` and a `kid` from the website's
 * relay JWKS. Sent to the relay as `Authorization: Bearer <jwt>`.
 */
export interface WebsiteRelayTokenClaims {
  iss: string; // "https://watchfaces.coroslink.com"
  aud: string; // "relay.coroslink.com"
  sub: string; // website user id
  client_id: WebsiteClientId;
  sid: string; // website app session id
  iat: number;
  exp: number; // at most iat + 600
  jti: string;
}

// ---------------------------------------------------------------------------
// Environment (desktop) request signatures
// ---------------------------------------------------------------------------

/** Header that carries the environment's compact JWS on desktop calls. */
export const ENVIRONMENT_SIGNATURE_HEADER = "CorosLink-Environment-Signature";
/** `typ` of the environment request JWS protected header. */
export const ENVIRONMENT_SIGNATURE_TYP = "coroslink-env-request+jws";
/** `iat` must be within this many seconds of the relay's clock. */
export const SIGNATURE_MAX_SKEW_SECONDS = 60;

export const ENVIRONMENT_OPERATIONS = [
  "environment.link",
  "environment.recovery",
  "environment.unlink",
  "environment.activity",
] as const;
export type EnvironmentOperation = (typeof ENVIRONMENT_OPERATIONS)[number];

/**
 * Payload of the environment request JWS. Protected header:
 * `{ alg: "ES256", typ: ENVIRONMENT_SIGNATURE_TYP, kid: <RFC 7638 SHA-256
 * thumbprint of the environment's public JWK> }`. Signed with the
 * environment's P-256 key.
 *
 * `nonce` is generated by the desktop (at least 16 random bytes,
 * base64url) for every call and acts as the replay guard: the relay refuses a
 * nonce it has already seen for that environment.
 */
export interface EnvironmentSignaturePayload {
  /** The relay origin, e.g. "https://relay.coroslink.com". */
  aud: string;
  environmentId: string;
  op: EnvironmentOperation;
  nonce: string;
  iat: number;
  /** base64url(SHA-256(raw request body bytes)); the empty body hashes "". */
  bodySha256: string;
}

// ---------------------------------------------------------------------------
// Mint exchange (relay → https://<hostname>/v1/relay/mint → relay)
// ---------------------------------------------------------------------------

export const MINT_PATH = "/v1/relay/mint";
/** `typ` of the relay-signed mint request JWT. */
export const RELAY_MINT_REQUEST_TYP = "coroslink-relay-mint+jwt";
/** `typ` of the environment-signed mint response proof. */
export const ENVIRONMENT_MINT_RESPONSE_TYP = "coroslink-env-mint+jws";
export const MINT_REQUEST_LIFETIME_SECONDS = 120;
/** A minted credential may live at most this long. */
export const MINT_CREDENTIAL_MAX_LIFETIME_SECONDS = 600;
export const MINT_TIMEOUT_MS = 10_000;

/** The audience the relay puts on a mint request for one environment. */
export function mintRequestAudience(environmentId: string): string {
  return `coroslink-env:${environmentId}`;
}

/**
 * Claims of the mint request JWT. Protected header:
 * `{ alg: "ES256", typ: RELAY_MINT_REQUEST_TYP, kid: <relay key id> }`, signed
 * with RELAY_SIGNING_KEY. Desktops verify it against the keys published at
 * `GET /.well-known/jwks.json` and refuse a nonce they have already seen.
 */
export interface RelayMintRequestClaims {
  iss: string; // relay origin
  aud: string; // mintRequestAudience(environmentId)
  environmentId: string;
  userId: string; // the website user the phone signed in as
  jkt: string; // RFC 7638 thumbprint of the phone's DPoP key
  nonce: string;
  iat: number;
  exp: number; // iat + MINT_REQUEST_LIFETIME_SECONDS
}

/** Body of `POST /v1/relay/mint`. */
export interface MintHttpRequest {
  request: string; // the RelayMintRequestClaims JWT
}

/** 200 body of `POST /v1/relay/mint`. */
export interface MintHttpResponse {
  credential: string;
  expiresAt: string; // ISO 8601
  /** Compact JWS over EnvironmentMintResponseProof, signed by the environment key. */
  proof: string;
}

/**
 * Payload of the mint response proof. Protected header:
 * `{ alg: "ES256", typ: ENVIRONMENT_MINT_RESPONSE_TYP, kid: <environment key thumbprint> }`.
 */
export interface EnvironmentMintResponseProof {
  environmentId: string;
  nonce: string; // the request's nonce
  jkt: string; // the request's jkt
  credentialSha256: string; // base64url(SHA-256(UTF-8 credential))
  exp: number; // floor(expiresAt / 1000)
  iat: number;
}

